import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const skillRoot = path.join(root, 'skills', 'rwcar-agent');
const files = [
  'SKILL.md',
  'agents/openai.yaml',
  'references/errors-and-recovery.md',
  'references/tool-contracts.md',
  'references/workflows.md',
];
const digest = createHash('sha256');
for (const relative of files) {
  const content = await readFile(path.join(skillRoot, relative));
  digest.update(`${relative}\0`, 'utf8');
  digest.update(content);
  digest.update('\0', 'utf8');
}
const sha256 = `0x${digest.digest('hex')}`;
const manifest = {
  schemaVersion: 1,
  skill: 'rwcar-agent',
  version: '1.0.0',
  hashAlgorithm: 'sha256',
  hashScope: files,
  sha256,
};
await writeFile(path.join(skillRoot, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(
  path.join(root, 'src', 'config', 'rwcar-agent-manifest.js'),
  `// Generated by scripts/generate-agent-skill-manifest.mjs.\nexport const RWCAR_AGENT_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`,
);
const examplePath = path.join(root, '.env.example');
const example = await readFile(examplePath, 'utf8');
if (!/^AGENT_ALLOWED_MANIFEST_HASHES=.*$/m.test(example)) {
  throw new Error('.env.example is missing AGENT_ALLOWED_MANIFEST_HASHES');
}
await writeFile(examplePath, example.replace(/^AGENT_ALLOWED_MANIFEST_HASHES=.*$/m, `AGENT_ALLOWED_MANIFEST_HASHES=${sha256}`));
process.stdout.write(`${sha256}\n`);
